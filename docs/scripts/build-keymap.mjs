/**
 * Generate the keyboard reference from the editor's own keymap — core
 * bindings AND every plugin's contributed ones.
 *
 * The guide must never disagree with the app, so nothing here is typed by
 * hand: `apps/editor/src/keymap.ts` is transpiled with esbuild, imported,
 * and both default layouts are dumped to src/data/keymap.json, which the
 * KeymapTable component renders.
 *
 * Plugins matter here because the running app renders its shortcut editor
 * and on-screen keyboard from the UNION keymap (core ∪ contributions), so
 * a reference built from keymap.ts alone would quietly lose every binding
 * that moved into a plugin — the reflection cycle did in slice 2, and a
 * user looking it up would find nothing. A plugin's `src/manifest.ts` is
 * a standalone module importing only a TYPE from @battuta/api, so the
 * same transpile-and-import trick works on it.
 *
 * Re-run whenever a binding changes:
 *
 *   npm run keymap        (part of npm run build)
 */
import { mkdirSync, writeFileSync, readFileSync, readdirSync, existsSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { transform } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../..");
const source = join(repo, "apps/editor/src/keymap.ts");
const pluginsDir = join(repo, "packages/plugins");
const outFile = join(here, "../src/data/keymap.json");

/** Transpile one TypeScript module and import it. */
let tmpSeq = 0;
async function importTs(file) {
  const { code } = await transform(readFileSync(file, "utf8"), { loader: "ts", format: "esm", target: "node20" });
  const tmp = join(here, `.keymap.generated.${tmpSeq++}.mjs`);
  writeFileSync(tmp, code);
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    rmSync(tmp, { force: true });
  }
}

const { defaultKeymap } = await importTs(source);

// Every shipped plugin's contributed bindings, by plugin id.
const contributions = [];
if (existsSync(pluginsDir)) {
  for (const name of readdirSync(pluginsDir).sort()) {
    const manifestPath = join(pluginsDir, name, "src/manifest.ts");
    if (!existsSync(manifestPath)) continue;
    const { manifest } = await importTs(manifestPath);
    for (const b of manifest?.contributes?.keybindings ?? []) contributions.push({ plugin: manifest.id, binding: b });
  }
}

/** Human-facing key text: "S" is shift+s, "⌥1–5" is already display-ready. */
function keyText(binding) {
  const pretty = binding.keys.map((k) => {
    if (/^[A-Z]$/.test(k)) return `shift + ${k.toLowerCase()}`;
    if (k.length === 1 || /[–↑↓←→⌥⌃⇧⊞]/.test(k)) return k;
    return k;
  });
  const mods = `${binding.alt ? "alt + " : ""}${binding.shift && !binding.keys.some((k) => /^[A-Z]$/.test(k)) ? "shift + " : ""}`;
  return pretty.map((k) => (k.startsWith("shift + ") ? k : `${mods}${k}`));
}

// Groups in the order the guide introduces them.
const GROUP_ORDER = ["entry", "accidentals", "marks", "rhythm", "repeats", "system"];
const GROUP_TITLES = {
  entry: "Note entry",
  accidentals: "Accidentals",
  marks: "Marks and expression",
  rhythm: "Rhythm",
  repeats: "Repeats and form",
  system: "Navigation and system",
};

const layouts = {};
for (const layout of ["qwerty", "azerty"]) {
  const map = defaultKeymap(layout);
  const groups = new Map();
  const push = (id, b, plugin) => {
    if (!groups.has(b.group)) groups.set(b.group, []);
    groups.get(b.group).push({
      id,
      keys: keyText(b),
      label: b.label,
      when: b.when ?? null,
      locked: Boolean(b.locked),
      ...(plugin ? { plugin } : {}),
    });
  };
  for (const [id, b] of Object.entries(map)) push(id, b);
  for (const { plugin, binding } of contributions) {
    // A plugin never shadows a core action id (the keymap store drops it).
    if (map[binding.command]) continue;
    const perLayout = binding.layouts?.[layout];
    push(binding.command, { ...binding, keys: perLayout?.keys ?? binding.keys, shift: perLayout?.shift ?? binding.shift }, plugin);
  }
  layouts[layout] = [...groups.entries()]
    .sort((a, b) => GROUP_ORDER.indexOf(a[0]) - GROUP_ORDER.indexOf(b[0]))
    .map(([group, actions]) => ({ group, title: GROUP_TITLES[group] ?? group, actions }));
}

const total = layouts.qwerty.reduce((sum, g) => sum + g.actions.length, 0);
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `${JSON.stringify(
    { generatedFrom: "apps/editor/src/keymap.ts + packages/plugins/*/src/manifest.ts", note: "Generated by scripts/build-keymap.mjs — do not edit by hand.", layouts },
    null,
    2,
  )}\n`,
);

console.log(`keymap: ${total} actions (${contributions.length} contributed by plugins) × 2 layouts → src/data/keymap.json`);
