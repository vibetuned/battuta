/**
 * Generate the keyboard reference from the editor's own keymap.
 *
 * The guide must never disagree with the app, so nothing here is typed by
 * hand: `apps/editor/src/keymap.ts` is transpiled with esbuild, imported,
 * and both default layouts are dumped to src/data/keymap.json, which the
 * KeymapTable component renders. Re-run whenever a binding changes:
 *
 *   npm run keymap        (part of npm run build)
 */
import { mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { transform } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, "../..");
const source = join(repo, "apps/editor/src/keymap.ts");
const outFile = join(here, "../src/data/keymap.json");

// Transpile the TypeScript source and import it as a module.
const ts = readFileSync(source, "utf8");
const { code } = await transform(ts, { loader: "ts", format: "esm", target: "node20" });
const tmp = join(here, ".keymap.generated.mjs");
writeFileSync(tmp, code);
let defaultKeymap;
try {
  ({ defaultKeymap } = await import(pathToFileURL(tmp).href));
} finally {
  rmSync(tmp, { force: true });
}

/** Human-facing key text: "S" is shift+s, "⌥1–5" is already display-ready. */
function keyText(binding) {
  const pretty = binding.keys.map((k) => {
    if (/^[A-Z]$/.test(k)) return `shift + ${k.toLowerCase()}`;
    if (k.length === 1 || /[–↑↓←→⌥⌃⇧⊞]/.test(k)) return k;
    return k;
  });
  const mods = `${binding.alt ? "alt + " : ""}${binding.shift && !binding.keys.some((k) => /^[A-Z]$/.test(k)) ? "shift + " : ""}`;
  return pretty.map((k) => (k.startsWith("shift + ") ? k : `${mods}${k}`));
}

// Groups in the order the guide introduces them.
const GROUP_ORDER = ["entry", "accidentals", "marks", "rhythm", "repeats", "system"];
const GROUP_TITLES = {
  entry: "Note entry",
  accidentals: "Accidentals",
  marks: "Marks and expression",
  rhythm: "Rhythm",
  repeats: "Repeats and form",
  system: "Navigation and system",
};

const layouts = {};
for (const layout of ["qwerty", "azerty"]) {
  const map = defaultKeymap(layout);
  const groups = new Map();
  for (const [id, b] of Object.entries(map)) {
    if (!groups.has(b.group)) groups.set(b.group, []);
    groups.get(b.group).push({
      id,
      keys: keyText(b),
      label: b.label,
      when: b.when ?? null,
      locked: Boolean(b.locked),
    });
  }
  layouts[layout] = [...groups.entries()]
    .sort((a, b) => GROUP_ORDER.indexOf(a[0]) - GROUP_ORDER.indexOf(b[0]))
    .map(([group, actions]) => ({ group, title: GROUP_TITLES[group] ?? group, actions }));
}

const total = layouts.qwerty.reduce((sum, g) => sum + g.actions.length, 0);
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `${JSON.stringify(
    { generatedFrom: "apps/editor/src/keymap.ts", note: "Generated by scripts/build-keymap.mjs — do not edit by hand.", layouts },
    null,
    2,
  )}\n`,
);

console.log(`keymap: ${total} actions × 2 layouts → src/data/keymap.json`);
